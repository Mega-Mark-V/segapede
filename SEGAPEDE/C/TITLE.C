int Title(void){
int fadeTime = 30;
int titleTime = 120;
int i, j;
int interrupted = 0;
short workpal[64];

  WaitTOF();
  ReadControllers();
  SendBlock32(titleCells, 0, sizeof(titleCells));
  for(i = 0; i < 28; i++){
    SendBlock32(&titleScreen[40*i], 0xc000+128*i, 80);
  }
  WaitTOF();
  FadeIn(palette, fadeTime);
  for(i = 0; i < titleTime; i++){
    ReadControllers();
    WaitTOF();
    if(stickEdges1 & JOYSTART){
      interrupted = 1;
      break;
    }
  }
  for(i = fadeTime-1; i >= 0; i--){
    for(j = 0; j < 64; j++){
      workpal[j] = palette[j];
    }
    InterpolateFullPalette(0, i, fadeTime, &workpal);
    SendPalettes(workpal);
    ReadControllers();
    WaitTOF();
    if(stickEdges1 & JOYSTART){
      interrupted = 1;
    }
  }
  return interrupted;
}


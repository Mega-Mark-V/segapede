static short bsearchtan(long d){
short j, k, m;

  j = 90;
  k = 0;
  for(;;){
    m = (j+k)/2;
    if(j <= k+1) break;
    if(tanTable[m] >= d){
      j = m;
    } else {
      k = m;
    }
  }
  return m;
}

short atan2(long x, long y){
short t;

  x /= 256;
  if(x < 0){
    if(y < 0){
      t = 180 + bsearchtan(y/x);
    } else {
      if(y == 0) return 180;
      t = 180 - bsearchtan(-y/x);
    }
  } else {
    if(y < 0){
      if(x == 0) return 270;
      t = 360 - bsearchtan(-y/x);
    } else {
      if(y == 0) return 0;
      if(x == 0) return 90;
      t = bsearchtan(y/x);
    }
  }
  return t;
}

